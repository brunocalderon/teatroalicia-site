import { spawnSync } from "node:child_process"
import { existsSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const backgroundPath = path.join(root, "public/background.jpg")
const outputPath = path.join(root, "src/lib/form-page-background.generated.ts")
const publicDir = path.join(root, "public")

const HD_SOURCES = {
  avif: path.join(publicDir, "background.avif"),
  webp: path.join(publicDir, "background.webp"),
  jpeg: backgroundPath,
}

const HD_URLS = {
  avif: "/background.avif",
  webp: "/background.webp",
  jpeg: "/background.jpg",
}

function runMagick(args) {
  return spawnSync("magick", args, { encoding: "buffer" })
}

if (!existsSync(backgroundPath)) {
  throw new Error(`Missing ${backgroundPath}`)
}

const lqip = runMagick([
  backgroundPath,
  "-resize",
  "36x",
  "-blur",
  "0x3",
  "-quality",
  "22",
  "-strip",
  "jpg:-",
])

if (lqip.status !== 0 || !lqip.stdout?.length) {
  console.warn(
    "generate-form-background-lqip: ImageMagick unavailable; keeping existing generated file.",
  )
  process.exit(0)
}

const avif = runMagick([
  backgroundPath,
  "-strip",
  "-quality",
  "42",
  "-define",
  "avif:speed=6",
  HD_SOURCES.avif,
])

const webp = runMagick([
  backgroundPath,
  "-strip",
  "-quality",
  "52",
  "-define",
  "webp:method=6",
  HD_SOURCES.webp,
])

if (avif.status !== 0) {
  console.warn("generate-form-background-lqip: AVIF encode failed; skipping file.")
}
if (webp.status !== 0) {
  console.warn("generate-form-background-lqip: WebP encode failed; skipping file.")
}

const dataUri = `data:image/jpeg;base64,${lqip.stdout.toString("base64")}`

const hdImageSet = `image-set(url(${JSON.stringify(HD_URLS.avif)}) type("image/avif"), url(${JSON.stringify(HD_URLS.webp)}) type("image/webp"), url(${JSON.stringify(HD_URLS.jpeg)}) type("image/jpeg"))`

const hdSources = [HD_URLS.avif, HD_URLS.webp, HD_URLS.jpeg]

const source = `/** Generated by scripts/generate-form-background-lqip.mjs — do not edit. */
export const FORM_PAGE_BACKGROUND_HD = ${JSON.stringify(HD_URLS.avif)} as const

export const FORM_PAGE_BACKGROUND_HD_SOURCES = ${JSON.stringify(hdSources)} as const

export const FORM_PAGE_BACKGROUND_HD_IMAGE_SET =
  ${JSON.stringify(hdImageSet)} as const

export const FORM_PAGE_BACKGROUND_LQIP_DATA_URI =
  ${JSON.stringify(dataUri)} as const
`

writeFileSync(outputPath, source, "utf8")
console.log(`Wrote ${outputPath} (${dataUri.length} chars LQIP)`)